#!/usr/bin/env bash
# Report-only privacy counts. The process must receive its own environment.
set -euo pipefail
if [[ -z "${HOST:-}" || -z "${RAILS_ENV:-}" || -z "${MI_RETENTION_CUTOFF:-}" || -z "${MI_RETENTION_LOGIN_TOKEN_CUTOFF:-}" ]]; then
  echo 'usage: set HOST, RAILS_ENV, MI_RETENTION_CUTOFF and MI_RETENTION_LOGIN_TOKEN_CUTOFF to your reviewed values' >&2
  exit 64
fi
if [[ ! "$MI_RETENTION_CUTOFF" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ || ! "$MI_RETENTION_LOGIN_TOKEN_CUTOFF" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]]; then
  echo 'retention_status failed=invalid_cutoff_format' >&2
  exit 64
fi
cd "$(dirname "${BASH_SOURCE[0]}")/.."
export REPORT_CONTACT_BEFORE="${REPORT_CONTACT_BEFORE:-$MI_RETENTION_CUTOFF}"
export REPORT_REVIEW_BEFORE="${REPORT_REVIEW_BEFORE:-$MI_RETENTION_CUTOFF}"
export REPORT_PHOTO_BEFORE="${REPORT_PHOTO_BEFORE:-$MI_RETENTION_CUTOFF}"
export REPORT_COORDINATES_BEFORE="${REPORT_COORDINATES_BEFORE:-$MI_RETENTION_CUTOFF}"
export CITIZEN_PHONE_BEFORE="${CITIZEN_PHONE_BEFORE:-$MI_RETENTION_CUTOFF}"
export VIBER_LINKAGE_BEFORE="${VIBER_LINKAGE_BEFORE:-$MI_RETENTION_CUTOFF}"
export VIBER_BUSINESS_CONTACT_BEFORE="${VIBER_BUSINESS_CONTACT_BEFORE:-$MI_RETENTION_CUTOFF}"
export VOLUNTEER_AVAILABILITY_BEFORE="${VOLUNTEER_AVAILABILITY_BEFORE:-$MI_RETENTION_CUTOFF}"
export KOMSILUK_POST_BODY_BEFORE="${KOMSILUK_POST_BODY_BEFORE:-$MI_RETENTION_CUTOFF}"
export KOMSILUK_DELIVERY_BEFORE="${KOMSILUK_DELIVERY_BEFORE:-$MI_RETENTION_CUTOFF}"
export CHAT_FEEDBACK_BEFORE="${CHAT_FEEDBACK_BEFORE:-$MI_RETENTION_CUTOFF}"
export PARTNER_PRIVATE_CONTACT_BEFORE="${PARTNER_PRIVATE_CONTACT_BEFORE:-$MI_RETENTION_CUTOFF}"
export PARTNER_VERIFICATION_DOCUMENT_BEFORE="${PARTNER_VERIFICATION_DOCUMENT_BEFORE:-$MI_RETENTION_CUTOFF}"
export COMMUNITY_REVIEW_REASON_BEFORE="${COMMUNITY_REVIEW_REASON_BEFORE:-$MI_RETENTION_CUTOFF}"
export OPERATOR_MESSAGE_BODY_BEFORE="${OPERATOR_MESSAGE_BODY_BEFORE:-$MI_RETENTION_CUTOFF}"
export CHANNEL_CONNECTION_BEFORE="${CHANNEL_CONNECTION_BEFORE:-$MI_RETENTION_CUTOFF}"
export CHANNEL_CONNECTION_CHALLENGE_BEFORE="${CHANNEL_CONNECTION_CHALLENGE_BEFORE:-$MI_RETENTION_CUTOFF}"
export MESSAGING_ATTEMPT_BEFORE="${MESSAGING_ATTEMPT_BEFORE:-$MI_RETENTION_CUTOFF}"
export MESSAGING_SUPPRESSION_BEFORE="${MESSAGING_SUPPRESSION_BEFORE:-$MI_RETENTION_CUTOFF}"
export ACCOUNT_NOTIFICATION_BEFORE="${ACCOUNT_NOTIFICATION_BEFORE:-$MI_RETENTION_CUTOFF}"
export LOGIN_TOKEN_BEFORE="${LOGIN_TOKEN_BEFORE:-$MI_RETENTION_LOGIN_TOKEN_CUTOFF}"
export REPORT_COORDINATE_PRECISION="${REPORT_COORDINATE_PRECISION:-2}"
exec bundle exec rails runner script/lib/mi_retention_status.rb
