# frozen_string_literal: true

require "digest"
require "rails-html-sanitizer"

module DecidimApp
  module Bijeljina
    module Milica
      # Bounded presentation of prepared public notices, never a new source
      # interpretation. Structured shortening requires a complete round-trip
      # against the known parser's current text and content-version inputs.
      module EventAnswer
        ELECTRICITY_PARSER_VERSION = "electricity_outage_parser_v3"
        MAX_SOURCE_TEXT = 2_000
        MAX_FACT_TEXT = 1_000
        QUALIFIERS = {
          "source_facts_unconfirmed" => "unconfirmed_facts",
          "geographic_scope_unconfirmed" => "unconfirmed_area",
          "event_time_unconfirmed" => "unconfirmed_time",
          "partial_geographic_coverage" => "partial_coverage",
          "possible_geographic_overlap" => "possible_overlap"
        }.freeze

        class << self
          def call(event:, locale:, warning_codes:)
            original = { "title" => clean(event.title), "summary" => clean(event.summary) }
            return if original.values.any? { |value| value.length > MAX_SOURCE_TEXT }

            body = electricity_body(event, original, locale:) || deduplicated_body(original)
            return if body.empty?

            qualifiers = qualifiers(event, locale:, warning_codes:)
            body = localize(body, locale)
            text = ([body] + qualifiers.values).join(" ")
            # If the complete safe fallback does not fit, do not pretend that
            # truncation is summarization. Keep the caller's existing behavior.
            return if text.length > MAX_FACT_TEXT

            { "answer_shape" => "service_event_v1", "notice_body" => body, "notice_qualifiers" => qualifiers,
              "source_text" => original, "text" => text }
          rescue I18n::MissingTranslationData
            # Presentation is optional; retain the existing complete fact text
            # when a locale is unavailable instead of failing the source read.
            nil
          end

          private

          def electricity_body(event, original, locale:)
            return unless supported_electricity?(event)

            metadata = event.extraction_metadata
            affected = event.affected_text.to_s
            return unless matching_electricity_version?(event, metadata, affected)
            return unless original == electricity_original(event, metadata, affected)

            parts = [translate("planned_electricity", locale:, affected:)]
            { "feeder" => ["asset", :asset], "tj" => ["service_unit", :unit], "reason" => ["reason", :reason] }.each do |field, (key, argument)|
              value = metadata[field].to_s
              parts << translate(key, locale:, **{ argument => value }) unless value.empty?
            end
            parts.join(" ")
          end

          def supported_electricity?(event)
            return false unless [:parser_version, :event_type, :affected_text].all? { |field| event.respond_to?(field) }
            return false unless event.source_key == "electricity_outages" && event.parser_version == ELECTRICITY_PARSER_VERSION
            return false unless event.event_type == "planned_outage" && %w(scheduled ongoing).include?(event.lifecycle)

            complete_source_window?(event)
          end

          def complete_source_window?(event)
            return false unless event.starts_at && event.ends_at && event.ends_at > event.starts_at

            metadata = event.extraction_metadata
            metadata["operator_review"].blank? && metadata["complete"] != false && metadata["timezone"] == "Europe/Sarajevo"
          end

          def matching_electricity_version?(event, metadata, affected)
            values = [ELECTRICITY_PARSER_VERSION, metadata["tj"], metadata["feeder"], affected, metadata["reason"], metadata["raw_from"], metadata["raw_to"]]
            event.content_version == Digest::SHA256.hexdigest(values.join("|"))
          end

          # Reconstructed from the parser's own formatter, never a second copy
          # of the wording: the round-trip below is only meaningful if both
          # sides are generated by the same code. A notice written before the
          # format changed simply fails the comparison and keeps its complete
          # text, which is the intended conservative outcome.
          def electricity_original(event, metadata, affected)
            summary = ElectricityOutageParser.citizen_summary(
              affected:,
              starts_at: event.starts_at.in_time_zone("Europe/Sarajevo"),
              ends_at: event.ends_at.in_time_zone("Europe/Sarajevo"),
              reason: metadata["reason"]
            )
            { "title" => clean(ElectricityOutageParser.citizen_title(affected)), "summary" => clean(summary) }
          end

          def deduplicated_body(original)
            title, summary = original.values_at("title", "summary")
            return summary if title.empty? || title == summary || summary.start_with?("#{title}: ", "#{title}. ")
            return title if summary.empty? || title.end_with?(": #{summary}")

            [title, summary].join(": ")
          end

          def qualifiers(event, locale:, warning_codes:)
            values = QUALIFIERS.each_with_object({}) do |(code, key), result|
              next unless warning_codes.include?(code)

              result[code] = localize(I18n.t("decidim_app.city_service_events.bot.#{key}", locale:, raise: true), locale)
            end
            if warning_codes.include?("place_name_context_not_service_coverage")
              context = CityServicePlaceContext.notice(event, locale:)
              values["place_name_context_not_service_coverage"] = localize(context, locale) unless context.empty?
            end
            values
          end

          def translate(key, locale:, **values)
            clean(I18n.t("decidim.bih.dialogue.notice_#{key}", locale:, raise: true, **values))
          end

          def localize(value, locale)
            Decidim::Bih::Transliterator.localize(clean(value), locale:)
          end

          def clean(value)
            Rails::HTML5::FullSanitizer.new.sanitize(value.to_s).gsub(/[\x00-\x08\x0b\x0c\x0e-\x1f]/, "").squish
          end
        end
      end
    end
  end
end
